"""Convert an 8-pixel-high BDF bitmap font into a Zephyr CFB font source.

The output is column-packed (CFB_FONT_MONO_VPACKED): one byte per glyph
column, least significant bit at the top, which is the SSD1306's native
layout. Only printable ASCII is converted.

    tools/bdf_to_cfb.py 5x8.bdf font5x8 > src/font_5x8.c

src/font_5x8.c was generated from misc-fixed 5x8.bdf (public domain), from
https://gitlab.freedesktop.org/xorg/font/misc-misc
"""

import sys

FIRST, LAST = 0x20, 0x7E


def parse_bdf(path):
    glyphs, props = {}, {}
    with open(path) as f:
        lines = iter(f.read().splitlines())

    for line in lines:
        key, _, value = line.partition(" ")
        if key in ("FONTBOUNDINGBOX", "FONT_ASCENT"):
            props[key] = [int(v) for v in value.split()]
        elif key == "STARTCHAR":
            code, bbx, rows = None, None, []
            for line in lines:
                key, _, value = line.partition(" ")
                if key == "ENCODING":
                    code = int(value)
                elif key == "BBX":
                    bbx = [int(v) for v in value.split()]
                elif key == "BITMAP":
                    for line in lines:
                        if line == "ENDCHAR":
                            break
                        rows.append(int(line, 16))
                    break
            glyphs[code] = (bbx, rows)

    return props, glyphs


def column_bytes(bbx, rows, cell_w, ascent):
    w, h, xoff, yoff = bbx
    row_bits = (w + 7) // 8 * 8
    top = ascent - (h + yoff)
    cols = [0] * cell_w

    for r, bits in enumerate(rows):
        y = top + r
        for c in range(w):
            x = xoff + c
            if bits & (1 << (row_bits - 1 - c)) and 0 <= x < cell_w and 0 <= y < 8:
                cols[x] |= 1 << y

    return cols


def main():
    path, name = sys.argv[1], sys.argv[2]
    props, glyphs = parse_bdf(path)
    cell_w, cell_h = props["FONTBOUNDINGBOX"][:2]
    ascent = props["FONT_ASCENT"][0]

    if cell_h != 8:
        sys.exit(f"{path}: cell is {cell_h} px high, expected 8")

    print("/* SPDX-License-Identifier: GPL-3.0-only */")
    print()
    print(f"/* Generated by tools/bdf_to_cfb.py from {path.rsplit('/', 1)[-1]}. Do not edit. */")
    print()
    print("#include <zephyr/display/cfb.h>")
    print()
    print(f"static const uint8_t {name}_glyphs[{LAST - FIRST + 1}][{cell_w}] = {{")
    for code in range(FIRST, LAST + 1):
        cols = column_bytes(*glyphs[code], cell_w, ascent)
        hexes = ", ".join(f"0x{b:02x}" for b in cols)
        label = "space" if code == 0x20 else "backslash" if code == 0x5C else chr(code)
        print(f"\t{{ {hexes} }}, /* {label} */")
    print("};")
    print()
    print(f"FONT_ENTRY_DEFINE({name}, {cell_w}, {cell_h}, CFB_FONT_MONO_VPACKED,")
    print(f"\t\t  {name}_glyphs, 0x{FIRST:02x}, 0x{LAST:02x});")


if __name__ == "__main__":
    main()
