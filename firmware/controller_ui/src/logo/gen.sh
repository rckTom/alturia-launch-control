#!/bin/sh
# Regenerates ui_logo.c: the Alturia Launch Control logo as a 1-bit alpha
# (A1) LVGL image for the splash screens. The panel has no grey, so the
# logo is thresholded rather than anti-aliased.
#
# Needs rsvg-convert, ImageMagick and python3. VARIANT picks the logo from
# design/logo (liftoff, rocket-a, rocket-i), WIDTH its width in pixels.
set -e
cd "$(dirname "$0")"

VARIANT=${VARIANT:-liftoff}
WIDTH=${WIDTH:-340}
SVG=../../../../design/logo/$VARIANT/alturia-launch-control-$VARIANT-mono.svg

rsvg-convert -w "$WIDTH" "$SVG" |
	magick png:- -background white -alpha remove -threshold 50% pbm:- |
	python3 -c '
import sys
data = sys.stdin.buffer.read()
# P4: "P4" whitespace width whitespace height single-whitespace raster
fields = data.split(maxsplit=3)
w, h, raster = int(fields[1]), int(fields[2]), fields[3]
stride = (w + 7) // 8
assert len(raster) == stride * h
# PBM 1 is black, which is where the logo is opaque, as A1 wants
print("/* Generated by gen.sh from %s, do not edit */" % sys.argv[1])
print()
print("#include <lvgl.h>")
print()
print("static const uint8_t logo_map[] = {")
for y in range(h):
    row = raster[y * stride:(y + 1) * stride]
    print("\t" + ", ".join("0x%02x" % b for b in row) + ",")
print("};")
print()
print("const lv_image_dsc_t ui_logo = {")
print("\t.header = {")
print("\t\t.magic = LV_IMAGE_HEADER_MAGIC,")
print("\t\t.cf = LV_COLOR_FORMAT_A1,")
print("\t\t.w = %d," % w)
print("\t\t.h = %d," % h)
print("\t\t.stride = %d," % stride)
print("\t},")
print("\t.data_size = sizeof(logo_map),")
print("\t.data = logo_map,")
print("};")
' "$(basename "$SVG")" > ui_logo.c
echo "ui_logo.c: $VARIANT, $WIDTH px wide"
